const norm = (s: string) => s.replace(/\s|학과|학부|전공|계열|대학/g, "");

/** 입력한 학과명에서 계열을 추론한다. 못 찾으면 null. */
export function facultyOf(major: string): Faculty | null {
  if (!major) return null;
  const m = norm(major);
  if (!m) return null;
  for (const [faculty, kws] of FACULTY_KEYWORDS) {
    if (kws.some((kw) => m.includes(kw))) return faculty;
  }
  return null;
}

/** 사용자가 고른 계열(우선) 또는 학과에서 추론한 계열. */
export function resolveFaculty(selectedFaculty: string, major: string): Faculty | null {
  if (selectedFaculty && (FACULTIES as readonly string[]).includes(selectedFaculty)) {
    return selectedFaculty as Faculty;
  }
  return facultyOf(major);
}
